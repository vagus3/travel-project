      ),
      body: SingleChildScrollView(
        padding: const EdgeInsets.fromLTRB(20, 20, 20, 40),
        child: Text(
          body,
          style: TextStyle(
            fontSize: 14,
            height: 1.7,
            color: colors.textSecondary,
          ),
        ),
      ),
    );
  }
}

